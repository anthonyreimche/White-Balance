// Writes src/camera-presets.data.ts from darktable's data/wb_presets.json
// (GPL-3.0-or-later): each camera's own white balance presets as the channel
// multipliers its raw files are balanced with, green-normalized. Only the
// presets at fine-tuning 0 are kept, one per name, in the camera's own order;
// the Kelvin-named ones ("5000K", "D55") are dropped because the Temp slider
// already sets Kelvin, and so is "Black & White".
//
//   node scripts/camera-presets.mjs <wb_presets.json> <darktable commit>

import { readFileSync, writeFileSync } from "node:fs";

const [input, commit] = process.argv.slice(2);
if (!input || !commit) {
  console.error("usage: node scripts/camera-presets.mjs <wb_presets.json> <darktable commit>");
  process.exit(1);
}

const SKIPPED = /^(\d+K|D\d\d|Black & White)$/;
const round = (v) => Math.round(v * 10000) / 10000;

const source = JSON.parse(readFileSync(input, "utf8"));
const cameras = [];
for (const { maker, models } of source.wb_presets) {
  for (const { model, presets } of models) {
    const seen = new Set();
    const kept = [];
    for (const { name, tuning, channels } of presets) {
      if ((tuning ?? 0) !== 0 || SKIPPED.test(name) || seen.has(name)) continue;
      const [r, g, b] = channels;
      if (!(r > 0 && g > 0 && b > 0)) continue;
      seen.add(name);
      kept.push([name, round(r / g), round(b / g)]);
    }
    if (kept.length > 0) cameras.push([maker, model, kept]);
  }
}

const body = cameras.map((c) => `  ${JSON.stringify(c)},`).join("\n");
writeFileSync(
  new URL("../src/camera-presets.data.ts", import.meta.url),
  `// Generated by scripts/camera-presets.mjs from darktable's data/wb_presets.json
// (GPL-3.0-or-later), commit ${commit}. Do not edit by hand.
//
// [maker, model, [preset name, red, blue][]]: the channel multipliers a camera
// balances its raw data with for each of its own white balance presets, with
// green at 1.

export type CameraPresetRow = readonly [maker: string, model: string, presets: readonly (readonly [name: string, red: number, blue: number])[]];

export const CAMERA_PRESETS: readonly CameraPresetRow[] = [
${body}
];
`,
);
console.log(`${cameras.length} cameras, ${cameras.reduce((n, c) => n + c[2].length, 0)} presets`);
