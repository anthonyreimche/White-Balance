// Writes src/camera-aliases.data.ts from rawspeed's data/cameras.xml: the
// Rebel and Kiss names Canon's bodies carry in the Americas and Japan, each
// with the EOS name the preset table lists the body under.
//
//   node scripts/camera-aliases.mjs <cameras.xml> <rawspeed commit>

import { readFileSync, writeFileSync } from "node:fs";

const [input, commit] = process.argv.slice(2);
if (!input || !commit) {
  console.error("usage: node scripts/camera-aliases.mjs <cameras.xml> <rawspeed commit>");
  process.exit(1);
}

const xml = readFileSync(input, "utf8");
const aliases = new Map();
for (const camera of xml.split(/<Camera\b/).slice(1)) {
  if (/make="([^"]*)"/.exec(camera)?.[1] !== "Canon") continue;
  const model = /<ID make="Canon" model="([^"]*)"/.exec(camera)?.[1];
  if (!model) continue;
  for (const [, name] of camera.matchAll(/<Alias(?: id="[^"]*")?>([^<]*)<\/Alias>/g)) {
    if (/rebel|kiss/i.test(name)) aliases.set(name, model);
  }
}

const body = [...aliases].map(([alias, model]) => `  [${JSON.stringify(alias)}, ${JSON.stringify(model)}],`).join("\n");
writeFileSync(
  new URL("../src/camera-aliases.data.ts", import.meta.url),
  `// Generated by scripts/camera-aliases.mjs from rawspeed's data/cameras.xml,
// commit ${commit}. Do not edit by hand.
//
// [EXIF model, model in the preset table]: Canon's Rebel and Kiss names.

export const CANON_ALIASES: readonly (readonly [alias: string, model: string])[] = [
${body}
];
`,
);
console.log(`${aliases.size} aliases`);
